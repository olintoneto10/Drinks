function trilhaDe(r) {
  // PAIS_DO_DRINK vem de momentos.js, que carrega depois — só é lido na renderização
  const pais = PAIS_DO_DRINK[r.id];
  if (pais && TRILHA_POR_PAIS[pais]) return TRILHA_POR_PAIS[pais];
  for (const i of r.ing) if (TRILHA_POR_BASE[i.id]) return TRILHA_POR_BASE[i.id];
  for (const [tag, busca, nome] of TRILHA_POR_TAG) {
    if (r.tags.includes(tag)) return { busca, nome };
  }
  return { busca: 'jazz standards bar', nome: 'jazz de bar' };
}

// Fica fora do bloco de história de propósito: receita própria e drink ainda
// sem verbete também merecem trilha.
function blocoTrilha(r) {
  const t = trilhaDe(r);
  return `<a class="btn btn-trilha" target="_blank" rel="noopener"
    href="https://open.spotify.com/search/${encodeURIComponent(t.busca)}">
    ♫ Ouvir ${esc(t.nome)} enquanto prepara</a>`;
}

function ocasiaoDerivada(r) {
  if (r.tags.includes('quente')) return 'Noite fria';
  if (r.tags.includes('sem-alcool')) return 'Qualquer hora do dia';
  if (r.tags.includes('cremoso')) return 'Depois do jantar';
  if (r.tags.includes('amargo')) return 'Aperitivo, antes de comer';
  if (r.tags.includes('tropical') || r.tags.includes('refrescante')) return 'Calor, tarde ao ar livre';
  return 'Noite, encontro com amigos';
}

// História guardada pelo usuário (escrita pela IA sob demanda)
function historiaDe(id) {
  return HISTORIAS[id] || Store.getHistorias()[id] || null;
}

// Bloco de história no modal. Sem história, mostra o convite — a lacuna de
// curiosidade é o que faz abrir o próximo drink.
function blocoHistoria(r, h) {
  const linha = (rotulo, valor) => valor
    ? `<li><span>${rotulo}</span><span>${valor}</span></li>` : '';

  // Sem verbete o drink não fica órfão: mostra o que se sabe de verdade — a
  // família a que pertence e a ficha derivada da própria receita. Nada aqui é
  // inventado; é por isso que o convite à IA vem separado e identificado.
  if (!h) {
    const ficha = `${r.familia ? `<p class="familia">${esc(r.familia)}</p>` : ''}
      <ul class="ficha-drink">
        ${linha('Ocasião', esc(ocasiaoDerivada(r)))}
        ${linha('Copo', esc(r.copo))}
      </ul>`;
    if (r.custom) return ficha;
    return `${ficha}
      <button class="btn btn-descobrir" data-descobrir="${r.id}">
        ✦ Descobrir a história deste drink</button>`;
  }

  // Três estados, não dois. 'real' é história pesquisada; 'lenda' é ficção
  // assumida em drink da casa; 'recriada' é o caso de um drink que existe num
  // balcão de verdade mas chegou aqui só por uma lista de ingredientes — a
  // bebida é real, as medidas são inferência. Chamar isso de "real" mentiria
  // sobre a precisão; chamar de "lenda" mentiria sobre a existência.
  const estado = h.lenda ? 'lenda' : h.recriado ? 'recriada' : 'real';
  const classe = h.lenda ? 'e-lenda' : h.recriado ? 'e-recriada' : 'e-real';
  const rotulo = h.lenda ? '✦ Lenda da casa' : h.recriado ? 'A reconstrução' : 'A história';
  const titulo = h.lenda ? 'História inventada para este app'
    : h.recriado ? 'Drink real, receita reconstruída a partir dos ingredientes conhecidos'
    : 'História pesquisada, de fontes verificáveis';
  const rodape = h.lenda
    ? 'História inventada para este app. A receita, não.'
    : h.recriado
      ? 'Drink de um balcão real, reconstruído aqui a partir dos ingredientes conhecidos. '
        + 'As proporções seguem o padrão clássico do estilo — não são a receita original da casa.'
      : '';

  return `
    <div class="historia${h.lenda ? ' e-lenda' : ''}${h.recriado ? ' e-recriada' : ''}">
      <span class="rotulo-hist">${rotulo}
        <b class="selo-verdade ${classe}" title="${titulo}">${estado}</b></span>
      <p>${h.historia}</p>
      ${h.criador ? `<p class="assinatura">— ${h.criador}</p>` : ''}
      ${blocoCuriosidade(h)}
      <ul class="ficha-drink">
        ${linha('Ocasião', h.ocasiao || ocasiaoDerivada(r))}
        ${linha('Temperatura', h.temperatura)}
        ${linha('Harmoniza com', h.harmoniza)}
        ${linha('Variações', h.variacoes)}
        ${linha('Na cultura', h.cultura)}
      </ul>
      ${rodape ? `<p class="rodape-lenda">${rodape}</p>` : ''}
      ${h.porIA ? '<p class="dica">História escrita pelo Especialista.</p>' : ''}
    </div>`;
}

// Pede ao Especialista a história de um drink sem verbete e guarda no aparelho
async function buscarHistoriaIA(receita) {
  const chave = Store.getApiKey();
  if (!chave) return null;
  const resposta = await askExpert(chave,
    'Você é um historiador de coquetelaria. Responda SOMENTE com um objeto JSON válido, ' +
    'sem cercas de código, com as chaves: origem (cidade/país e época), criador, historia ' +
    '(2 a 3 frases, em português do Brasil, tom de bartender culto; se a origem for ' +
    'disputada, diga "conta-se que"), curiosidade (1 frase surpreendente), ocasiao, ' +
    'temperatura, harmoniza, variacoes, cultura (filme, série ou fato cultural; se não ' +
    'houver, string vazia).',
    [{ role: 'user', content: `Conte a história do drink "${receita.nome}", feito com ${receita.ing.map(i => ING_MAP[i.id]?.nome || i.id).join(', ')}.` }]);
  const m = resposta.match(/\{[\s\S]*\}/);
  if (!m) return null;
  try {
    const dados = JSON.parse(m[0]);
    const guardadas = Store.getHistorias();
    guardadas[receita.id] = { ...dados, porIA: true };
    Store.setHistorias(guardadas);
    return guardadas[receita.id];
  } catch { return null; }
}
